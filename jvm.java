public class JvmComprehension {

    // При запуске класслоадеры (bootstrap, platform, application) загружают этот класс и нужные классы из JDK. Метаданные классов лежат в Metaspace. Для потока main создаётся стек, в нём фрейм main.

    public static void main(String[] args) { // args лежит в локальной переменной фрейма main

        int i = 1;                      // примитив просто пишется в локальную переменную фрейма main, в кучу ничего не идёт

        Object o = new Object();        // в heap создаётся объект Object, в стеке main сохраняется ссылка на него

        Integer ii = 2;                 // автобоксинг, вызывается Integer.valueOf(2).  2 попадает в кэш IntegerCache (-128..127), поэтому новый объект не создаётся - в переменную пишется ссылка на закэшированный объект из heap

        printAll(o, i, ii);             // в стеке появляется новый фрейм printAll. В него копируются ссылка o, значение i и ссылка ii. Сами объекты не копируются

        System.out.println("finished"); // литерал "finished" уже лежит в String Pool, новый объект не создаётся, строка просто выводится
    }

    private static void printAll(Object o, int i, Integer ii) { // здесь уже работает фрейм printAll: o, i, ii - его локальные переменные

        Integer uselessVar = 700;                   // 700 вне диапазона кэша, поэтому Integer.valueOf(700) создаёт новый объект в heap, ссылка кладётся в локальную переменную фрейма printAll

        System.out.println(o.toString() + i + ii);  // берётся System.out (объект PrintStream в heap), вызывается o.toString() - появляется строка в heap, потом конкатенация с i, затем с ii. Каждая конкатенация создаёт новую строку в heap. Итоговая строка уходит  в println, промежуточные строки становятся мусором
    }

    // После выхода из printAll его фрейм удаляется из стека. Объект Integer(700) больше ниоткуда не достижим — это кандидат на сборку мусора, minor GC его уберёт. А o и ii живы, потому что на них ссылается main.
    // GC roots — это локальные переменные в стеках активных потоков и статические поля. Всё, что от них недостижимо, считается мусором. Minor GC чистит молодое поколение (Eden и Survivor): туда попадают объект Object, строки из конкатенаций и Integer(700) после выхода из printAll. Old Gen - долгоживущие объекты: System.out, IntegerCache, литерал "finished". Metaspace GC не трогает, пока жив загрузчик классов.
    // Когда main заканчивается, его фрейм удаляется, поток завершается, и JVM останавливается, если нет других non-daemon потоков.
}
